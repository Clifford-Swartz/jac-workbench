"""
CAD Tool Server — standalone HTTP API for executing build123d geometry operations.

Runs on localhost:5050. JAC's extension calls this directly to execute CAD tools
generated by any model (cloud or local). No Flask dependency — uses built-in http.server.

Tools:
  - cad_execute: Run build123d Python code
  - transform_part: Translate, rotate, scale
  - measure: Get dimensions/volume
  - list_parts: List all current solids
  - export_stl: Export a part to STL
  - reset: Clear all geometry
"""

import json
import sys
import traceback
import logging
from http.server import HTTPServer, BaseHTTPRequestHandler
from pathlib import Path

log = logging.getLogger("cad_tools")

# Current session state
session_solids = []  # list of build123d Solid objects
session_history = []  # list of operations performed


def _lazy_import():
    """Import build123d on first use to avoid slow startup."""
    global bd, Solid, Location, Axis, scale
    import build123d as bd
    from build123d import Solid, Location, Axis, scale
    return bd


def _build_parts_info(solids: list) -> list:
    """Build parts info with tessellated mesh data for Three.js rendering."""
    parts_info = []
    for i, s in enumerate(solids):
        try:
            bb = s.bounding_box()
            info = {
                "index": i,
                "dims": [round(bb.size.X, 1), round(bb.size.Y, 1), round(bb.size.Z, 1)],
                "volume": round(s.volume, 0),
                "center": [round((bb.min.X+bb.max.X)/2, 1),
                           round((bb.min.Y+bb.max.Y)/2, 1),
                           round((bb.min.Z+bb.max.Z)/2, 1)],
            }
            # Tessellate to triangles for Three.js
            try:
                verts, indices = s.tessellate(0.1)
                positions = []
                for v in verts:
                    positions.extend([round(v.X, 3), round(v.Y, 3), round(v.Z, 3)])
                faces = []
                for tri in indices:
                    faces.extend(tri)
                info["mesh"] = {"positions": positions, "indices": faces}
            except Exception:
                pass  # fall back to bounding box rendering
            parts_info.append(info)
        except Exception:
            parts_info.append({"index": i, "dims": [0, 0, 0], "volume": 0, "center": [0, 0, 0]})
    return parts_info


def exec_cad_code(code: str, target_index=None, isolate_indices=None) -> dict:
    """Execute build123d Python code and update session geometry."""
    global session_solids
    _lazy_import()

    namespace = {}
    if isolate_indices is not None:
        valid = [i for i in isolate_indices if 0 <= i < len(session_solids)]
        if not valid:
            return {"ok": False, "error": f"No valid indices: {isolate_indices}"}
        namespace["INPUT_SHAPES"] = [session_solids[i] for i in valid]
    else:
        namespace["INPUT_SHAPES"] = session_solids

    if target_index is not None:
        if target_index < 0 or target_index >= len(session_solids):
            return {"ok": False, "error": f"Invalid target_index: {target_index}"}
        namespace["TARGET_PART"] = session_solids[target_index]

    full_code = code
    if "from build123d import" not in code:
        full_code = "from build123d import *\n" + code

    try:
        exec(full_code, namespace)
    except Exception:
        return {"ok": False, "error": traceback.format_exc()}

    result = namespace.get("RESULT")
    if result is None:
        # RESULT = None means "clear/delete geometry"
        session_solids = []
        return {"ok": True, "n_parts": 0, "parts": []}

    # Filter out None values from lists (e.g. RESULT = [solid, None])
    if isinstance(result, (list, tuple)):
        result_list = [r for r in result if r is not None]
    else:
        result_list = [result]

    if not result_list:
        session_solids = []
        return {"ok": True, "n_parts": 0, "parts": []}

    # Update session solids
    if isolate_indices is not None:
        valid = sorted([i for i in isolate_indices if 0 <= i < len(session_solids)])
        new_solids = list(session_solids)
        for i in reversed(valid):
            del new_solids[i]
        insert_pos = min(valid) if valid else len(new_solids)
        for j, s in enumerate(result_list):
            new_solids.insert(insert_pos + j, s)
        session_solids = new_solids
    elif target_index is not None:
        if isinstance(result, (list, tuple)):
            session_solids[target_index:target_index + 1] = result_list
        else:
            session_solids[target_index] = result
    else:
        session_solids = result_list

    # Build geometry info + mesh data for response
    parts_info = _build_parts_info(session_solids)

    session_history.append({"tool": "cad_execute", "code": code[:200]})
    return {"ok": True, "n_parts": len(session_solids), "parts": parts_info}


def transform_part(target: int, transform: str, **kwargs) -> dict:
    """Apply a transform to a part."""
    global session_solids
    _lazy_import()

    if target < 0 or target >= len(session_solids):
        return {"ok": False, "error": f"Invalid target: {target}"}

    solid = session_solids[target]
    try:
        if transform == "translate":
            dx, dy, dz = kwargs.get("vector", [0, 0, 0])
            session_solids[target] = solid.move(Location((dx, dy, dz)))
        elif transform == "rotate":
            ax = {"X": bd.Axis.X, "Y": bd.Axis.Y, "Z": bd.Axis.Z}.get(kwargs.get("axis", "Z"), bd.Axis.Z)
            session_solids[target] = solid.rotate(ax, kwargs.get("angle", 0))
        elif transform == "scale":
            session_solids[target] = bd.scale(solid, kwargs.get("factor", 1.0))
        else:
            return {"ok": False, "error": f"Unknown transform: {transform}"}
    except Exception:
        return {"ok": False, "error": traceback.format_exc()}

    session_history.append({"tool": "transform", "target": target, "transform": transform})
    return {"ok": True, "message": f"Applied {transform} to part #{target}"}


def delete_parts(targets: list) -> dict:
    """Delete parts by index."""
    global session_solids
    valid = sorted([i for i in targets if 0 <= i < len(session_solids)], reverse=True)
    for i in valid:
        del session_solids[i]
    parts = _build_parts_info(session_solids) if session_solids else []
    return {"ok": True, "n_parts": len(session_solids), "parts": parts}


def duplicate_part(target: int, offset=None) -> dict:
    """Duplicate a part with optional offset."""
    global session_solids
    _lazy_import()
    if target < 0 or target >= len(session_solids):
        return {"ok": False, "error": f"Invalid target: {target}"}
    solid = session_solids[target]
    if offset:
        copy = solid.move(bd.Location((offset[0], offset[1], offset[2])))
    else:
        copy = solid.move(bd.Location((20, 0, 0)))
    session_solids.append(copy)
    return {"ok": True, "n_parts": len(session_solids), "parts": _build_parts_info(session_solids)}


def mirror_part(target: int, plane: str = "YZ", keep_original: bool = True) -> dict:
    """Mirror a part across a plane."""
    global session_solids
    _lazy_import()
    if target < 0 or target >= len(session_solids):
        return {"ok": False, "error": f"Invalid target: {target}"}
    solid = session_solids[target]
    try:
        plane_map = {"YZ": bd.Plane.YZ, "XZ": bd.Plane.XZ, "XY": bd.Plane.XY}
        p = plane_map.get(plane, bd.Plane.YZ)
        mirrored = bd.mirror(solid, about=p)
        if keep_original:
            session_solids.append(mirrored)
        else:
            session_solids[target] = mirrored
    except Exception:
        return {"ok": False, "error": traceback.format_exc()}
    return {"ok": True, "n_parts": len(session_solids), "parts": _build_parts_info(session_solids)}


def boolean_op(op: str, target_a: int, target_b: int) -> dict:
    """Boolean operation between two parts: union, cut, intersect."""
    global session_solids
    _lazy_import()
    if target_a < 0 or target_a >= len(session_solids):
        return {"ok": False, "error": f"Invalid target_a: {target_a}"}
    if target_b < 0 or target_b >= len(session_solids):
        return {"ok": False, "error": f"Invalid target_b: {target_b}"}
    a, b = session_solids[target_a], session_solids[target_b]
    try:
        if op == "union":
            result = a + b
        elif op == "cut":
            result = a - b
        elif op == "intersect":
            result = a & b
        else:
            return {"ok": False, "error": f"Unknown op: {op}"}
        # Remove both originals, insert result
        for i in sorted([target_a, target_b], reverse=True):
            del session_solids[i]
        session_solids.insert(min(target_a, target_b), result)
    except Exception:
        return {"ok": False, "error": traceback.format_exc()}
    return {"ok": True, "n_parts": len(session_solids), "parts": _build_parts_info(session_solids)}


def measure(target: int = None) -> dict:
    """Measure a part or all parts, with mesh data."""
    _lazy_import()
    parts = _build_parts_info(session_solids)
    if target is not None:
        parts = [p for p in parts if p.get("index") == target]
    return {"ok": True, "parts": parts}


def list_parts() -> dict:
    """List all current solids."""
    return measure()


def export_stl(target: int, filename: str = "export.stl") -> dict:
    """Export a part to STL. If filename is an absolute path, save there directly."""
    _lazy_import()
    if target < 0 or target >= len(session_solids):
        return {"ok": False, "error": f"Invalid target: {target}"}
    out_path = Path(filename)
    if not out_path.is_absolute():
        out_dir = Path.home() / ".jac" / "cad_out"
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / filename
    try:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        session_solids[target].export_stl(str(out_path))
        return {"ok": True, "path": str(out_path), "size_kb": round(out_path.stat().st_size / 1024)}
    except Exception:
        return {"ok": False, "error": traceback.format_exc()}


def load_step(filepath: str) -> dict:
    """Load a STEP file into the session."""
    global session_solids
    _lazy_import()
    from build123d import import_step
    try:
        result = import_step(filepath)
        if isinstance(result, (list, tuple)):
            session_solids = list(result)
        else:
            session_solids = [result] if result else []
        return {"ok": True, "n_parts": len(session_solids), **measure()}
    except Exception:
        return {"ok": False, "error": traceback.format_exc()}


def reset() -> dict:
    """Clear all geometry."""
    global session_solids, session_history
    session_solids = []
    session_history = []
    return {"ok": True, "message": "Session cleared."}


def get_geometry_context() -> str:
    """Build geometry context string for LLM system prompt."""
    if not session_solids:
        return "No geometry loaded. Use cad_execute to create geometry."
    lines = [f"Assembly: {len(session_solids)} solid(s)\n"]
    for i, s in enumerate(session_solids):
        try:
            bb = s.bounding_box()
            lines.append(f"  [{i}] {bb.size.X:.1f}x{bb.size.Y:.1f}x{bb.size.Z:.1f}mm "
                        f"vol={s.volume:.0f}mm³ "
                        f"center=({(bb.min.X+bb.max.X)/2:.1f}, {(bb.min.Y+bb.max.Y)/2:.1f}, {(bb.min.Z+bb.max.Z)/2:.1f})")
        except Exception:
            lines.append(f"  [{i}] (measurement error)")
    return "\n".join(lines)


# ── HTTP API ────────────────────────────────────────────────────────────────

TOOL_MAP = {
    "cad_execute": lambda args: exec_cad_code(args["code"], args.get("target_index"), args.get("isolate_indices")),
    "transform_part": lambda args: transform_part(args["target"], args["transform"], **{k: v for k, v in args.items() if k not in ("target", "transform")}),
    "delete_parts": lambda args: delete_parts(args["targets"]),
    "duplicate_part": lambda args: duplicate_part(args["target"], args.get("offset")),
    "mirror_part": lambda args: mirror_part(args["target"], args.get("plane", "YZ"), args.get("keep_original", True)),
    "boolean_op": lambda args: boolean_op(args["op"], args["target_a"], args["target_b"]),
    "measure": lambda args: measure(args.get("target")),
    "list_parts": lambda args: list_parts(),
    "export_stl": lambda args: export_stl(args["target"], args.get("filename", "export.stl")),
    "load_step": lambda args: load_step(args["filepath"]),
    "reset": lambda args: reset(),
    "geometry_context": lambda args: {"ok": True, "context": get_geometry_context()},
}


class CadHandler(BaseHTTPRequestHandler):
    def do_POST(self):
        length = int(self.headers.get('Content-Length', 0))
        body = json.loads(self.rfile.read(length)) if length else {}

        tool_name = body.get("tool", "")
        args = body.get("args", {})

        handler = TOOL_MAP.get(tool_name)
        if not handler:
            self.respond(400, {"ok": False, "error": f"Unknown tool: {tool_name}"})
            return

        try:
            result = handler(args)
            self.respond(200, result)
        except Exception:
            self.respond(500, {"ok": False, "error": traceback.format_exc()})

    def do_GET(self):
        if self.path == "/health":
            self.respond(200, {"status": "ok", "n_parts": len(session_solids)})
        elif self.path == "/parts":
            self.respond(200, list_parts())
        elif self.path == "/context":
            self.respond(200, {"context": get_geometry_context()})
        else:
            self.respond(404, {"error": "not found"})

    def respond(self, code, data):
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(json.dumps(data).encode())

    def log_message(self, format, *args):
        log.info(format % args)


def main():
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 5050
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    server = HTTPServer(("127.0.0.1", port), CadHandler)
    log.info("CAD tool server on http://127.0.0.1:%d", port)
    server.serve_forever()


if __name__ == "__main__":
    main()
